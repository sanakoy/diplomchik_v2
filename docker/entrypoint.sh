#!/bin/sh
# Останавливаемся на первой ошибке: если миграции не применились,
# приложение стартовать не должно
set -e

echo "Применяю миграции..."
alembic upgrade head

echo "Запускаю: $*"
# exec, чтобы uvicorn стал главным процессом контейнера и получал сигналы
# остановки напрямую — иначе docker stop не даст ему завершиться штатно
exec "$@"
